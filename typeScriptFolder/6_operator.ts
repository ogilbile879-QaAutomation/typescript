//Arithmatic operator

let a=10
let b=20
console.log(a+b);
console.log(a-b);
console.log(a*b);
console.log(a/b);

//unary operator
let c=0;
console.log(c++);//0,1
console.log(++c);//2
console.log(c);//2
console.log(c--);//2,1
console.log(--c);//0

//Assignment Operator

let x=10;
console.log((x+=5));//15
console.log(x-=5);//10
console.log(x*=5);//50
console.log(x/=5);//10

//comparision operator
let n=10;
let m=20;

console.log(n==m);//false
console.log(n!=m);//true
console.log(n>m);//false
console.log(n<m);//true
console.log(n>=m);//false
console.log(n<=m);//true

//logical operator

console.log(3<12 && 4>2);//true
console.log(5<3 && 5>12);//false





















